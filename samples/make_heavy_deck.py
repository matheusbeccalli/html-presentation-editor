"""
make_heavy_deck.py - writes samples/heavy-deck.html, a big FAKE deck for performance tests.

SPEC 8.3 / 8.4: "one heavy deck (40+ slides, many images)" and "a 50-slide deck with
20 MB of images must stay responsive". The file is about 20 MB, so it is generated on
demand instead of being stored in Git (see .gitignore).

Standard library only. The images are made-up noise pictures (PNG written by hand),
which compress badly on purpose so the file really is large.

Usage:  python samples/make_heavy_deck.py [number_of_slides]
"""

import base64
import random
import struct
import sys
import zlib
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent / "heavy-deck.html"
IMAGE_WIDTH, IMAGE_HEIGHT = 300, 220


def png_bytes(width, height, rng):
    """Build a PNG file in memory: a colour gradient with random noise."""
    base_r, base_g, base_b = rng.randrange(256), rng.randrange(256), rng.randrange(256)
    rows = []
    for y in range(height):
        row = bytearray([0])  # filter type 0 (none) at the start of every row
        for x in range(width):
            noise = rng.randrange(64)
            row += bytes(((base_r + x // 2 + noise) % 256, (base_g + y // 2 + noise) % 256, (base_b + noise) % 256))
        rows.append(bytes(row))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)  # 8-bit RGB
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(b"".join(rows), 6)) + chunk(b"IEND", b"")


def data_uri(rng):
    return "data:image/png;base64," + base64.b64encode(png_bytes(IMAGE_WIDTH, IMAGE_HEIGHT, rng)).decode("ascii")


def slide_html(number, rng):
    eid = number * 10
    return f"""
<section class="slide" data-slide-id="s{number}">
  <div class="el" data-type="text" data-id="e{eid + 1}" style="left:64px; top:40px; width:1152px; height:60px; z-index:1"><h2>Unidade {number:02d} — visão operacional</h2></div>
  <img class="el" data-type="image" data-id="e{eid + 2}" style="left:64px; top:140px; width:540px; height:396px; z-index:2" alt="Foto {number}a" src="{data_uri(rng)}">
  <img class="el" data-type="image" data-id="e{eid + 3}" style="left:676px; top:140px; width:540px; height:396px; z-index:3" alt="Foto {number}b" src="{data_uri(rng)}">
  <div class="el" data-type="text" data-id="e{eid + 4}" style="left:64px; top:570px; width:1152px; height:100px; z-index:4"><p>Receita fictícia: R$ {rng.randrange(20, 400)} mn · Margem: {rng.randrange(8, 35)}% · Funcionários: {rng.randrange(50, 900)}</p></div>
  <aside class="notes">Notas do slide {number}.</aside>
</section>"""


def main():
    slide_count = int(sys.argv[1]) if len(sys.argv) > 1 else 50
    rng = random.Random(2026)  # fixed seed: the same file every time
    slides = "".join(slide_html(n, rng) for n in range(1, slide_count + 1))
    html = f"""<!DOCTYPE html>
<!-- SAMPLE DECK - FAKE DATA ONLY. Generated by samples/make_heavy_deck.py for performance tests. -->
<html lang="pt-BR">
<head>
<meta charset="utf-8">
<meta name="deck-format" content="1">
<title>Deck pesado ({slide_count} slides)</title>
<style>
  :root {{ --font-heading: Calibri, Arial, sans-serif; --font-body: Calibri, Arial, sans-serif;
          --color-primary: #CC092F; --color-accent: #1F2A44; --color-text: #222; --color-bg: #fff; }}
  body {{ margin: 0; font-family: var(--font-body); color: var(--color-text); }}
  .slide {{ position: relative; width: 1280px; height: 720px; overflow: hidden; background: var(--color-bg); }}
  .el {{ position: absolute; box-sizing: border-box; }}
  .el h2, .el p {{ margin: 0; }}
  .el h2 {{ font-family: var(--font-heading); font-size: 34px; color: var(--color-accent); }}
  .el p {{ font-size: 22px; }}
  img.el {{ object-fit: cover; }}
</style>
</head>
<body>{slides}
</body>
</html>
"""
    OUTPUT.write_text(html, encoding="utf-8")
    print(f"Wrote {OUTPUT.name}: {slide_count} slides, {OUTPUT.stat().st_size / (1024 * 1024):.1f} MB")


if __name__ == "__main__":
    main()
